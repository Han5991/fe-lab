test('일별 추이 — 면은 선을 바닥까지 닫는다', () => {
  // 면 path는 바닥 변을 점마다 찍어 4KB가 넘는다. 통째로 스냅샷하면 diff가
  // 읽히지 않아 이 파일이 막으려는 일(눈으로 훑고 넘어가기)이 다시 생긴다.
  // 곡선은 위에서 이미 잠갔으니, 여기서는 **닫히는 방식**만 본다.
  const d = monotoneAreaPath(SERIES, DEFAULT_BOX);
  const floor = DEFAULT_BOX.height - DEFAULT_BOX.padBottom;
  // 곡선부(위 모서리)는 선 path와 **글자 단위로 같다** — 면과 선이 어긋나면
  // 채움이 선 밖으로 비어져 나온다.
  expect(d.startsWith(monotoneLinePath(SERIES, DEFAULT_BOX))).toBe(true);
  // 되돌아오는 바닥 변은 왼쪽 끝에서 닫힌다(d3는 마지막 구간도 C로 낸다).
  expect(d.endsWith(`,${DEFAULT_BOX.padLeft},${floor}Z`)).toBe(true);
});

