/**
 * `/admin` 차트의 **기하 스냅샷**.
 *
 * 이 파일이 있는 이유는 사각지대다 — `/admin`은 로그인 게이트 뒤라 배포된
 * 프리뷰에서 열리지 않고, `check-parity`의 대조 대상(`PARITY_PAGES`)에도
 * 없다. **두 검증 장치 어느 쪽도 이 화면을 보지 않는다.** 그 틈에서
 * `preserveAspectRatio="none"`이 한참 살아남았다: viewBox를 가로로만 늘려
 * 축 글자가 뭉개지고 커서 점이 타원이 됐는데, 빌드도 테스트도 전부 통과했다.
 *
 * 픽셀을 보는 것이 아니라 **좌표 문자열을 못 박는다.** 이 앱의 vitest는
 * node 하나라(화면을 렌더하지 않는다) 그림이 아니라 계약을 잠그는 것이
 * 이 저장소의 방식이고, 고쳐야 할 것 대부분은 어차피 좌표에서 갈린다.
 * 스냅샷이 바뀌면 의도한 변경인지 판단한 뒤 받아들이면 된다 — 조용히
 * 지나가지만 않으면 된다.
 *
 * 인라인 스냅샷인 이유는 diff다. 별도 파일이면 리뷰에서 "스냅샷 갱신됨"
 * 한 줄로 접히는데, 그러면 이 파일이 막으려는 바로 그 일이 다시 일어난다.
 */

